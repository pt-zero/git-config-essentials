[ -z "$(git config --global --get core.editor)" ] && git config --global core.editor "vim"
git config --global alias.cr "clone --recursive"
git config --global alias.st "status"
git config --global alias.ci "commit"
git config --global alias.br "branch"
git config --global alias.co "checkout"
git config --global alias.sb "show-branch"
git config --global alias.cpk "cherry-pick"
git config --global alias.lg "log --graph --date=short --pretty=format:'%C(green)%h %C(magenta)(%ar)%C(yellow)%d %C(cyan)%an: %C(reset)%s' --date-order"
git config --global alias.hist "log --graph --date=short --pretty=format:'%C(green)%h %C(magenta)(%ar)%C(yellow)%d %C(cyan)%an: %C(reset)%s' --date-order --all"
git config --global alias.tree "forest --pretty=format:'%C(green)%h %C(magenta)(%ar) %C(cyan)%an: %C(reset)%s'"
git config --global alias.trees "forest --pretty=format:'%C(green)%h %C(magenta)(%ar) %C(cyan)%an: %C(reset)%s' --all"
git config --global alias.subinit "submodule update --init --recursive"
git config --global alias.subclean "submodule foreach --recursive 'git clean -fxd'"
git config --global alias.maxgc "gc --prune=now --aggressive"
git config --global alias.pullall "pull --recurse-submodules --rebase"
git config --global alias.pushall "push --recurse-submodules=on-demand"
git config --global alias.dif """!f() { git diff \"\$1~1\" \"\$1\"; }; f"""
git config --global color.ui "always"
git config --global push.recurseSubmodules "check"
